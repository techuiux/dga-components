#!/usr/bin/env node
/**
 * Generates one Code Connect template per icon in the Figma library
 * "Icons - Platforms Code" (4,389 component sets), mapping each to Hugeicons.
 *
 *   FIGMA_ACCESS_TOKEN=... node scripts/figma-icons.mjs          # fetch from the Figma API
 *   node scripts/figma-icons.mjs --from icons.json                # offline: [{ node_id, name }]
 *
 * Output: figma/icons/generated/*.figma.ts (gitignored; CI regenerates before publishing).
 *
 * Each icon set has Style (Stroke/Twotone/Duotone/Solid/Bulk) x Type (Rounded/Sharp/Standard).
 * Stroke + Rounded imports from the free package @hugeicons/core-free-icons when the icon
 * exists there; every other combination imports from the matching Pro package
 * @hugeicons-pro/core-<style>-<type> (needs a Hugeicons Pro licence).
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const FILE_KEY = 'ZXWLjobkULtvqFSxgB2Kmh';
const FILE_URL = `https://www.figma.com/design/${FILE_KEY}/Icons---Platforms-Code--Community-`;
const ICON_PAGE = /❖ ICONS/; // the MISC ICONS page holds brand logos and flags, which have no Hugeicons equivalent
const OUT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../figma/icons/generated');

// ---- 1. Icon list -------------------------------------------------------------------------
async function loadIcons() {
  const from = process.argv.indexOf('--from');
  if (from > 0) return JSON.parse(fs.readFileSync(process.argv[from + 1], 'utf8'));
  const token = process.env.FIGMA_ACCESS_TOKEN;
  if (!token) throw new Error('Set FIGMA_ACCESS_TOKEN or pass --from <json>');
  const res = await fetch(`https://api.figma.com/v1/files/${FILE_KEY}/component_sets`, { headers: { 'X-Figma-Token': token } });
  if (!res.ok) throw new Error(`Figma API ${res.status}: ${await res.text()}`);
  const { meta } = await res.json();
  return meta.component_sets.filter((s) => ICON_PAGE.test(s.containing_frame?.pageName ?? ''));
}

// ---- 2. Figma name -> Hugeicons export ------------------------------------------------------
// ICONS_NODE_MODULES lets CI install the icon package outside the pnpm workspace.
const require = createRequire(process.env.ICONS_NODE_MODULES ? path.join(process.env.ICONS_NODE_MODULES, 'resolve.js') : import.meta.url);
let free = [];
try {
  free = Object.keys(require('@hugeicons/core-free-icons')).filter((k) => k.endsWith('Icon'));
} catch {
  console.warn('@hugeicons/core-free-icons not installed: every icon will use the Pro packages');
}
const WORDS = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine'];
const norm = (s) => s.toLowerCase().replace(/\+/g, 'plus').replace(/[^a-z0-9]/g, '');
const freeByKey = new Map(free.map((k) => [norm(k.slice(0, -4)), k]));

// Hugeicons spells standalone digits and a leading digit as words (3d-move -> ThreeDMove, tv-4-k -> TvFourK).
function candidates(name) {
  const parts = name.toLowerCase().replace(/\+/g, '-plus').split(/[^a-z0-9]+/).filter(Boolean);
  const words = parts.map((p) => (/^[0-9]$/.test(p) ? WORDS[p] : p));
  const lead = (s) => s.replace(/^([0-9])/, (d) => WORDS[d]);
  const keys = [parts.join(''), lead(parts.join('')), words.join(''), lead(words.join(''))];
  if (/^c(plus)+$/.test(norm(name))) keys.push('cpp');
  return [...new Set(keys)];
}
const pascal = (name) => {
  const p = name.toLowerCase().replace(/\+/g, '-plus').split(/[^a-z0-9]+/).filter(Boolean).map((s) => s[0].toUpperCase() + s.slice(1)).join('');
  return (/^[0-9]/.test(p) ? WORDS[p[0]][0].toUpperCase() + WORDS[p[0]].slice(1) + p.slice(1) : p) + 'Icon';
};
function resolve(name) {
  for (const k of candidates(name)) if (freeByKey.has(k)) return { exp: freeByKey.get(k), inFree: true };
  return { exp: pascal(name), inFree: false };
}

// ---- 3. Templates ---------------------------------------------------------------------------
const template = (icon, exp, inFree) => `// url=${FILE_URL}?node-id=${icon.node_id.replace(':', '-')}
// source=${inFree ? '@hugeicons/core-free-icons' : '@hugeicons-pro'}
// component=${exp}
// Generated by scripts/figma-icons.mjs from Figma icon "${icon.name.replace(/\n/g, ' ')}". Do not edit.
import figma from 'figma'
const instance = figma.selectedInstance
const style = instance.getEnum('Style', { Stroke: 'stroke', Twotone: 'twotone', Duotone: 'duotone', Solid: 'solid', Bulk: 'bulk' }) || 'stroke'
const type = instance.getEnum('Type', { Rounded: 'rounded', Sharp: 'sharp', Standard: 'standard' }) || 'rounded'
const pkg = ${inFree ? "style === 'stroke' && type === 'rounded' ? '@hugeicons/core-free-icons' : " : ''}'@hugeicons-pro/core-' + style + '-' + type

export default {
  example: figma.code\`<HugeiconsIcon icon={${exp}} />\`,
  imports: ['import { HugeiconsIcon } from "@hugeicons/react"', 'import { ${exp} } from "' + pkg + '"'],
  id: 'icon',
  metadata: { nestable: true, props: { name: ${JSON.stringify(icon.name)}, style, type } },
}
`;

const icons = await loadIcons();
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
let freeCount = 0;
const proOnly = [];
for (const icon of icons) {
  const { exp, inFree } = resolve(icon.name);
  if (inFree) freeCount++;
  else proOnly.push(`${icon.name} -> ${exp}`);
  const file = `${icon.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'icon'}-${icon.node_id.replace(':', '-')}.figma.ts`;
  fs.writeFileSync(path.join(OUT, file), template(icon, exp, inFree));
}
console.log(`Generated ${icons.length} icon templates in ${path.relative(process.cwd(), OUT)}`);
console.log(`${freeCount} found in @hugeicons/core-free-icons; ${proOnly.length} only as Pro (name guessed):`);
if (proOnly.length) console.log('  ' + proOnly.slice(0, 50).join('\n  ') + (proOnly.length > 50 ? `\n  ...and ${proOnly.length - 50} more` : ''));

import figma from 'figma'
const instance = figma.selectedInstance

const rtl = instance.getEnum('RTL', { True: true, False: false })
const label = rtl ? instance.getString('Text AR') : instance.getString('Text EN')
// Radix requires a `value`; derive a slug from the label as a starting point.
const value = label.toLowerCase().trim().replace(/\s+/g, '-')

// Selected is driven by <Tabs value>, Size lives on <Tabs>, so neither is a trigger prop.
// Closed / Open only exist on the "More Tab" overflow variant.
const disabled = instance.getEnum('State', {
  Default: false,
  Hovered: false,
  Pressed: false,
  Focused: false,
  Disabled: true,
  Closed: false,
  Open: false,
})
const moreTab = instance.getEnum('More Tab', { Yes: true, No: false })

const hasIcon = instance.getBoolean('Icon')
const iconSwap = instance.getInstanceSwap('🔁 Swap Icon')
let icon
if (hasIcon && iconSwap && iconSwap.type === 'INSTANCE') icon = iconSwap.executeTemplate().example

export default {
  // The overflow "More" tab is generated by <TabsList overflow>, not authored by hand.
  example: moreTab
    ? figma.code`{/* "More" tab: rendered automatically by <TabsList overflow /> */}`
    : figma.code`<TabsTrigger value="${value}"${icon ? figma.code` startIcon={${icon}}` : ''}${disabled ? ' disabled' : ''}>
  ${label}
</TabsTrigger>`,
  imports: ['import { TabsTrigger } from "@dev-dga/react"'],
  id: 'tabs-trigger',
  metadata: { nestable: true, props: { value } },
}
